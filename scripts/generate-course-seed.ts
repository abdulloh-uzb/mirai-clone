// Generates supabase/seed/course.sql from scripts/course-content (ticket 01).
// Run: pnpm db:seed:course. The output is deterministic: re-running makes no diff.
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import {
  blockContentByLocaleSchema,
  COURSE_LOCALES,
} from "../src/lib/course/blocks";
import type { Question } from "./course-content/helpers";
import {
  COURSE_SLUG,
  examQuestions,
  LESSON_MIN_SECONDS,
  sections,
} from "./course-content";

function lit(value: unknown): string {
  const text = typeof value === "string" ? value : JSON.stringify(value);
  if (text.includes("$q$")) throw new Error("content contains the $q$ quote");
  return `$q$${text}$q$`;
}

function validateQuestion(question: Question) {
  const correct = question.options.filter((o) => o.correct).length;
  if (question.options.length !== 4 || correct !== 1) {
    throw new Error(`${question.key}: needs 4 options with exactly 1 correct`);
  }
  for (const locale of COURSE_LOCALES) {
    if (!question.text[locale])
      throw new Error(`${question.key}: no ${locale}`);
    for (const option of question.options) {
      if (!option.text[locale])
        throw new Error(`${question.key}: option ${locale}`);
    }
  }
}

function questionSql(
  sectionPosition: number | null,
  question: Question,
): string[] {
  validateQuestion(question);
  return COURSE_LOCALES.map((locale) => {
    const options = question.options.map((o) => ({
      text: o.text[locale],
      correct: o.correct,
    }));
    const section = sectionPosition === null ? "null" : String(sectionPosition);
    return `select pg_temp.add_question(${section}, '${locale}', ${lit(question.text[locale])}, ${lit(question.explanation[locale])}, ${lit(options)}::jsonb);`;
  });
}

export function buildSql(): string {
  const out: string[] = [
    "-- GENERATED by scripts/generate-course-seed.ts (pnpm db:seed:course). Do not edit by hand.",
    "-- Ticket 01: original demo course content in en, ja, es and ru.",
    "",
    `create function pg_temp.section_id(sec integer) returns uuid language sql as $f$`,
    `  select s.id from public.sections s join public.courses c on c.id = s.course_id`,
    `  where c.slug = '${COURSE_SLUG}' and s.position = sec`,
    `$f$;`,
    "",
    `create function pg_temp.lesson_id(sec integer, pos integer) returns uuid language sql as $f$`,
    `  select l.id from public.lessons l where l.section_id = pg_temp.section_id(sec) and l.position = pos`,
    `$f$;`,
    "",
    `create function pg_temp.add_question(sec integer, loc text, q_text text, q_expl text, opts jsonb)`,
    `returns void language plpgsql as $f$`,
    `declare qid uuid;`,
    `begin`,
    `  insert into public.questions (section_id, locale, text, explanation)`,
    `  values (case when sec is null then null else pg_temp.section_id(sec) end, loc, q_text, q_expl)`,
    `  returning id into qid;`,
    `  insert into public.answer_options (question_id, text, is_correct)`,
    `  select qid, o ->> 'text', (o ->> 'correct')::boolean from jsonb_array_elements(opts) as o;`,
    `end`,
    `$f$;`,
    "",
  ];

  let lessonCount = 0;
  for (const { position, content } of sections) {
    if (content.lessons.length !== 3)
      throw new Error(`section ${position}: need 3 lessons`);
    if (content.quiz.length !== 10)
      throw new Error(`section ${position}: need 10 quiz questions`);
    out.push(`-- Section ${position}`);
    content.lessons.forEach((lesson, lessonIndex) => {
      lessonCount += 1;
      const lessonPosition = lessonIndex + 1;
      const title = Object.fromEntries(
        COURSE_LOCALES.map((l, i) => [l, lesson.title[i]]),
      );
      out.push(
        `insert into public.lessons (section_id, position, min_seconds, title) values (pg_temp.section_id(${position}), ${lessonPosition}, ${LESSON_MIN_SECONDS}, ${lit(title)}::jsonb);`,
      );
      lesson.blocks.forEach((block, blockIndex) => {
        const parsed = blockContentByLocaleSchema(block.type).parse(
          block.content,
        );
        out.push(
          `insert into public.lesson_blocks (lesson_id, position, type, content) values (pg_temp.lesson_id(${position}, ${lessonPosition}), ${blockIndex + 1}, '${block.type}', ${lit(parsed)}::jsonb);`,
        );
      });
    });
    for (const question of content.quiz)
      out.push(...questionSql(position, question));
    out.push("");
  }

  if (examQuestions.length < 60)
    throw new Error("the exam pool needs at least 60 questions");
  out.push("-- Final exam pool (section_id null)");
  for (const question of examQuestions)
    out.push(...questionSql(null, question));
  out.push("");
  out.push(
    "-- TODO(spec): demo minimums (60 s per lesson). The CA minimum is the sum of the lessons' minutes.",
    `update public.states set min_course_minutes = ${(lessonCount * LESSON_MIN_SECONDS) / 60} where code = 'CA';`,
    "",
  );
  return out.join("\n");
}

// One WebVTT file per video and language, made from the transcript.
function writeCaptions(root: string) {
  const dir = join(root, "public", "placeholder", "course", "captions");
  mkdirSync(dir, { recursive: true });
  for (const { content } of sections) {
    for (const lesson of content.lessons) {
      for (const block of lesson.blocks.filter((b) => b.type === "video")) {
        for (const locale of COURSE_LOCALES) {
          const { captionsSrc, transcript } = block.content[locale] as {
            captionsSrc: string;
            transcript: string;
          };
          const file = join(dir, captionsSrc.split("/").pop() ?? "");
          writeFileSync(
            file,
            `WEBVTT\n\n00:00:00.000 --> 00:00:30.000\n${transcript}\n`,
          );
        }
      }
    }
  }
}

if (process.argv[1] && import.meta.filename === process.argv[1]) {
  const root = join(import.meta.dirname, "..");
  const target = join(root, "supabase", "seed", "course.sql");
  writeFileSync(target, buildSql());
  writeCaptions(root);
  console.log(`wrote ${target}`);
}
